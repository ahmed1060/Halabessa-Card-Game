// Deterministic local asset packaging only. No cloud writes or deployment.
import 'dart:convert';
import 'dart:io';

Future<void> main(List<String> arguments) async {
  if (arguments.length != 1) {
    throw ArgumentError('Supply the exported choices JSON');
  }
  final packet = jsonDecode(await File(arguments.single).readAsString()) as Map;
  if (packet['schema'] != 1 || (packet['unchosen'] as List).isNotEmpty) {
    throw StateError('A complete schema-1 selection is required');
  }
  final selected = Map<String, dynamic>.from(packet['selected'] as Map);
  final catalog =
      jsonDecode(
            await File(
              'build/sound-options-2026-10-24/catalog.json',
            ).readAsString(),
          )
          as Map;
  final events = catalog['events'] as List;
  final expected = events
      .expand((e) => e['assetPaths'] as List)
      .cast<String>()
      .toSet();
  if (selected.keys.toSet().difference(expected).isNotEmpty ||
      expected.difference(selected.keys.toSet()).isNotEmpty) {
    throw StateError('Selection must cover exactly the registered audio keys');
  }
  final validated = <String, List<int>>{};
  final files = <String, String>{},
      labels = <String, String>{},
      hashes = <String, int>{};
  for (final entry in selected.entries) {
    final choice = entry.value as Map;
    final event =
        events.singleWhere((e) => (e['assetPaths'] as List).contains(entry.key))
            as Map;
    final candidate =
        (event['candidates'] as List).singleWhere(
              (c) => c['id'] == choice['choice'],
            )
            as Map;
    if (choice['event'] != event['id'] ||
        choice['file'] != candidate['file'] ||
        choice['fnv1a32'] != candidate['fnv1a32']) {
      throw StateError(
        'Selection does not match audition catalog: ${entry.key}',
      );
    }
    // Only trusted catalog paths identify input files; the uploaded JSON cannot
    // choose an arbitrary source/destination path or executable content.
    final bytes = await File(
      'build/sound-options-2026-10-24/${candidate['file']}',
    ).readAsBytes();
    var hash = 2166136261;
    for (final byte in bytes) {
      hash = ((hash ^ byte) * 16777619) & 0xffffffff;
    }
    if (hash != candidate['fnv1a32'] ||
        ascii.decode(bytes.sublist(0, 4)) != 'RIFF' ||
        ascii.decode(bytes.sublist(8, 12)) != 'WAVE') {
      throw StateError('Audition bytes changed: ${entry.key}');
    }
    final name =
        '${event['id']}-${candidate['id']}-${hash.toRadixString(16)}.wav';
    final asset = 'audio/defaults/2026-10-24/$name';
    validated[asset] = bytes;
    files[entry.key] = asset;
    labels[entry.key] = candidate['label'] as String;
    hashes[entry.key] = hash;
  }
  for (final entry in validated.entries) {
    final target = File('assets/${entry.key}');
    await target.parent.create(recursive: true);
    if (await target.exists()) {
      final old = await target.readAsBytes();
      if (base64Encode(old) != base64Encode(entry.value)) {
        throw StateError('Refusing to overwrite immutable asset');
      }
    } else {
      await target.writeAsBytes(entry.value);
    }
  }
  const encoder = JsonEncoder.withIndent('  ');
  await File('assets/audio/defaults/2026-10-24/selection.json').writeAsString(
    encoder.convert({
      'schema': 1,
      'localOnly': true,
      'date': '2026-10-24',
      'selected': selected,
      'bundledFiles': files,
      'fingerprints': hashes,
    }),
  );
  String literal(Map values) =>
      '{\n${values.entries.map((e) => '    ${jsonEncode(e.key)}: ${jsonEncode(e.value)},').join('\n')}\n  }';
  await File('lib/core/services/selected_audio_defaults.dart').writeAsString(
    '''// GENERATED by tool/install_selected_audio.dart from the approved audition export.
// Logical asset keys stay compatible with existing gameplay and admin overrides.
class SelectedAudioDefaults {
  static const files = <String, String>${literal(files)};
  static const labels = <String, String>${literal(labels)};
  static const fingerprints = <String, int>${literal(hashes)};
}
''',
  );
  stdout.writeln(
    'Packaged ${selected.length} routes, ${validated.length} exact WAV files. No remote setting changed.',
  );
}
